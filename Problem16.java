// problem 16: print numbers between 1 and 100 that are divisible by both 3 and 5
    
public class Problem16 {
    public static void main(String[] args){
    
        for(int i=1; i<=100; i++){
            if(i%3==0 && i%5==0){
                System.out.println(i);


            }
       
    }
    
}

}
    

